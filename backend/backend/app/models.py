import datetime
from sqlalchemy import (
    Column, Integer, String, Float, Boolean, DateTime, ForeignKey, Text
)
from sqlalchemy.orm import relationship
from app.database import Base


def now():
    return datetime.datetime.utcnow()


class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, nullable=False)
    email = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    created_at = Column(DateTime, default=now)

    # settings
    notifications_enabled = Column(Boolean, default=True)
    units = Column(String, default="metric")  # metric | imperial

    patients = relationship("PatientRecord", back_populates="owner", cascade="all, delete-orphan")
    predictions = relationship("Prediction", back_populates="owner", cascade="all, delete-orphan")
    chats = relationship("ChatMessage", back_populates="owner", cascade="all, delete-orphan")


class PatientRecord(Base):
    """One row per 'Patient Details' form submission (PatientForm.jsx)."""
    __tablename__ = "patient_records"

    id = Column(Integer, primary_key=True, index=True)
    owner_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    created_at = Column(DateTime, default=now)

    # Personal / lifestyle
    name = Column(String, default="Anonymous")
    age = Column(Integer)
    sex = Column(String)  # "0" female, "1" male
    height = Column(Float, nullable=True)
    weight = Column(Float, nullable=True)
    bmi = Column(Float, nullable=True)
    occupation = Column(String, nullable=True)
    smoking = Column(String, nullable=True)  # non-smoker | former | current
    alcohol = Column(String, nullable=True)  # none | moderate | heavy
    family_history = Column(String, nullable=True)
    physical_activity = Column(String, nullable=True)  # low | moderate | high
    daily_steps = Column(Integer, nullable=True)
    sleep_hours = Column(Float, nullable=True)
    stress_level = Column(Integer, default=2)
    diet_type = Column(String, nullable=True)
    water_intake = Column(Float, nullable=True)

    # Clinical (feed the ML model directly - matches Cleveland dataset encoding)
    cp = Column(Integer)          # 0-3 chest pain type
    trestbps = Column(Float)      # resting blood pressure
    chol = Column(Float)          # cholesterol
    fbs = Column(Integer)         # fasting blood sugar > 120 (0/1)
    restecg = Column(Integer)     # resting ECG (0-2)
    thalach = Column(Float)       # max heart rate achieved
    exang = Column(Integer)       # exercise induced angina (0/1)
    oldpeak = Column(Float)       # ST depression
    slope = Column(Integer)       # ST slope (0-2)
    ca = Column(Integer)          # number of major vessels (0-3)
    thal = Column(Integer)        # thalassemia (1-3)
    medications = Column(String, nullable=True)
    previous_heart_disease = Column(String, nullable=True)
    diabetes = Column(String, nullable=True)
    hypertension = Column(String, nullable=True)

    owner = relationship("User", back_populates="patients")
    predictions = relationship("Prediction", back_populates="patient", cascade="all, delete-orphan")


class Prediction(Base):
    """Result of running the ML model on a PatientRecord (Prediction.jsx -> Results.jsx)."""
    __tablename__ = "predictions"

    id = Column(Integer, primary_key=True, index=True)
    owner_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    patient_id = Column(Integer, ForeignKey("patient_records.id"), nullable=True)
    created_at = Column(DateTime, default=now)

    prediction = Column(Integer)       # 0 = low risk, 1 = high risk
    probability = Column(Float)        # 0-1
    risk_pct = Column(Float)           # 0-100, convenience field for the UI
    risk_level = Column(String)        # "Low Risk" | "High Risk"
    confidence = Column(Float)         # 0-1
    heart_age = Column(Integer, nullable=True)
    health_score = Column(Integer, nullable=True)
    recommendation = Column(Text, nullable=True)
    notes = Column(String, nullable=True)
    is_whatif = Column(Boolean, default=False)  # True if generated by the What-If simulator

    owner = relationship("User", back_populates="predictions")
    patient = relationship("PatientRecord", back_populates="predictions")


class UploadedReport(Base):
    """A file the user uploaded on the Medical Report page (Report.jsx)."""
    __tablename__ = "uploaded_reports"

    id = Column(Integer, primary_key=True, index=True)
    owner_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    filename = Column(String, nullable=False)
    content_type = Column(String, nullable=True)
    size_bytes = Column(Integer, nullable=True)
    stored_path = Column(String, nullable=False)
    created_at = Column(DateTime, default=now)

    owner = relationship("User")


class ChatMessage(Base):
    """AI Assistant chat history (AIAssistant.jsx)."""
    __tablename__ = "chat_messages"

    id = Column(Integer, primary_key=True, index=True)
    owner_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    role = Column(String)  # "user" | "assistant"
    content = Column(Text)
    created_at = Column(DateTime, default=now)

    owner = relationship("User", back_populates="chats")
